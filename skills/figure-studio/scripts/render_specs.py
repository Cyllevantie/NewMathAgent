#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""⑦'s default renderer: read ``figures/spec/*.json`` + ``figures/data/*.npz``.

Copy this file to ``figures/make_figures.py`` (or import it) and extend the
custom branch when a spec needs a bespoke composition.  The contract is:

    read  figures/spec/<id>.json      (semantic part is locked)
    read  figures/data/<id>.npz       (read-only)
    read  figures/<id>.lock.json      (verify before rendering)
    write figures/<id>.pdf/.svg/.png  + source_data/*.csv + <id>.meta.json

It never writes the bundle, the spec's semantic part or the lock.

Per-figure recovery: one broken figure does **not** block the others.  A
figure whose lock fails is skipped and reported; the healthy ones still
render (⑧/⑦ only need to redo the named figure, not the whole batch).

Usage:
    python skills/figure-studio/scripts/render_specs.py --root .
    python skills/figure-studio/scripts/render_specs.py --root . --figure q3_dryfront
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import figure_lock  # noqa: E402
import studio  # noqa: E402
try:
    import check_figure_mix  # noqa: E402
except Exception:                        # keep rendering if the checker is absent
    check_figure_mix = None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, default=Path.cwd())
    ap.add_argument("--figure", action="append", default=None,
                    help="render only this figure id (repeatable)")
    ap.add_argument("--include-duplicates", action="store_true",
                    help="也渲染与 plate hero 同源同图型的 3D 支撑图（默认跳过）")
    args = ap.parse_args(argv)

    root = args.root.resolve()
    skip_dupes = (set() if args.include_duplicates or check_figure_mix is None
                  else set(check_figure_mix.duplicate_ids(root)))
    # ⑦ owns `figures/make_figures.py`.  If it has not been written yet, leave a
    # working entry point so `save_figure` has a real script to hash/register.
    script = root / "figures" / "make_figures.py"
    if not script.is_file():
        script.parent.mkdir(parents=True, exist_ok=True)
        script.write_text(
            "# -*- coding: utf-8 -*-\n"
            "# generated by skills/figure-studio/scripts/render_specs.py\n"
            "import sys\n"
            "from pathlib import Path\n"
            "sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'skills/figure-studio/scripts'))\n"
            "import render_specs\n"
            "raise SystemExit(render_specs.main(['--root', str(Path(__file__).resolve().parents[1])]))\n",
            encoding="utf-8",
        )
    spec_dir = root / "figures" / "spec"
    wanted = list(args.figure or [])
    if wanted:
        specs = [spec_dir / f"{fid}.json" for fid in wanted]
    else:
        specs = sorted(spec_dir.glob("*.json")) if spec_dir.is_dir() else []

    problems = []
    renderable = []
    for path in specs:
        fid = path.stem
        if fid in skip_dupes:
            print(f"skip {fid}: 与 plate hero 同源同图型的 3D 重复图；"
                  f"bundle 保留给 plate 读，不再单独渲染")
            continue
        if not path.is_file():
            print(f"skip {fid}: 没有 figures/spec/{fid}.json")
            problems.append(fid)
            continue
        # check_meta=False: a stale meta.claim is fixed by re-rendering.  Data /
        # spec contract still gates this figure.
        issues = [i for i in figure_lock.verify(root, fid, check_meta=False)
                  if i["kind"] in ("data", "contract")]
        if issues:
            print(f"skip {fid}: figure lock 不通过（只跳过这一张，不影响其余）")
            for item in issues:
                print("   -", figure_lock.format_issue(item))
            problems.append(fid)
            continue
        renderable.append(fid)

    # Let each spec resolve its own template/language; mixing templates in one
    # workspace is rare but a spec's locked `template` is the authority.
    # Render one by one so a broken recipe on figure A does not abort figure B.
    rendered = []
    custom = []
    for fid in renderable:
        try:
            spec = studio.load_spec(root, fid)
        except ValueError as exc:
            print(f"skip {fid}: {exc}")
            problems.append(fid)
            continue
        if not spec:
            print(f"skip {fid}: spec 不可读")
            problems.append(fid)
            continue
        render = spec.get("render") or {}
        mode = render.get("mode") if isinstance(render, dict) else "declarative"
        if str(mode or "declarative") != "declarative":
            print(f"custom {fid}: 由 figures/make_figures.py 的自定义分支处理")
            custom.append(fid)
            continue
        try:
            rendered.append(studio.render_spec(spec, root))
        except Exception as exc:         # noqa: BLE001 - isolate one figure
            print(f"failed {fid}: {exc}")
            problems.append(fid)
    print(f"rendered {len(rendered)} figure(s); custom {len(custom)}; "
          f"skipped/failed {len(problems)}")
    for entry in rendered:
        print(" -", entry["artifacts"][0].rsplit("/", 1)[-1])
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
